#!/usr/bin/env python3
"""Count samples per dataset, split, and category for the experiments.

Inspects the JSONL metadata files used in training/evaluation and reports
counts broken down by method (deepfake category), real/fake label, and split.

Usage::

    python scripts/count_dataset_samples.py

Adjust the DATASET_PATHS dict below if your paths differ.
"""
from __future__ import annotations

import json
import os
import sys
from collections import Counter, defaultdict
from pathlib import Path


DATASET_PATHS = {
    "DD-VQA (train)": "/datasets/deepfake/ddvqa_prepared/train.jsonl",
    "DD-VQA (val)": "/datasets/deepfake/ddvqa_prepared/val.jsonl",
    "DD-VQA (test)": "/datasets/deepfake/ddvqa_prepared/test.jsonl",
    "DD-VQA loc (train)": "/datasets/deepfake/ddvqa_prepared/train_loc.jsonl",
    "DD-VQA loc (val)": "/datasets/deepfake/ddvqa_prepared/val_loc.jsonl",
    "DD-VQA loc (test)": "/datasets/deepfake/ddvqa_prepared/test_loc.jsonl",
    "FF++ cls (train)": "/datasets/deepfake/ff_classification/train.jsonl",
    "FF++ cls (val)": "/datasets/deepfake/ff_classification/val.jsonl",
    "FF++ cls (test)": "/datasets/deepfake/ff_classification/test.jsonl",
    "Celeb-DF-v2 (test)": "/datasets/deepfake/celebdf_prepared/test.jsonl",
    "WildDeepfake (test_sampled)": "/datasets/deepfake/wilddeepfake_prepared/test_sampled.jsonl",
    "WildDeepfake (test_full)": "/datasets/deepfake/wilddeepfake_prepared/test.jsonl",
}


def count_ddvqa_aggregate(paths: list[str]) -> dict | None:
    """Aggregate DD-VQA train+val+test: unique videos/images per method and question."""
    rows = []
    for path in paths:
        if not os.path.isfile(path):
            return None
        with open(path, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line:
                    rows.append(json.loads(line))

    if not rows:
        return None

    by_method = defaultdict(lambda: {"qa": 0, "images": set(), "videos": set()})
    by_question = defaultdict(lambda: {"qa": 0, "images": set(), "videos": set()})
    by_question_method = defaultdict(lambda: {"qa": 0, "images": set()})

    all_images = set()
    all_videos = set()

    for r in rows:
        method = r.get("method", "unknown")
        question = r.get("question", "").strip()
        image = r.get("image", "")
        video_id = r.get("video_id", "")

        by_method[method]["qa"] += 1
        if image:
            by_method[method]["images"].add(image)
            all_images.add(image)
        if video_id:
            by_method[method]["videos"].add(video_id)
            all_videos.add(video_id)

        if question:
            by_question[question]["qa"] += 1
            if image:
                by_question[question]["images"].add(image)
            if video_id:
                by_question[question]["videos"].add(video_id)

            cell = by_question_method[(question, method)]
            cell["qa"] += 1
            if image:
                cell["images"].add(image)

    method_order = [
        "Original", "Deepfakes", "Face2Face", "FaceSwap", "NeuralTextures", "FaceShifter"
    ]
    by_method_out = {}
    for method in method_order:
        if method in by_method:
            entry = by_method[method]
            by_method_out[method] = {
                "qa": entry["qa"],
                "images": len(entry["images"]),
                "videos": len(entry["videos"]),
            }

    by_question_out = {}
    for question, entry in sorted(by_question.items(), key=lambda x: -x[1]["qa"]):
        by_question_out[question] = {
            "qa": entry["qa"],
            "images": len(entry["images"]),
            "videos": len(entry["videos"]),
        }

    by_question_method_out = {}
    for question in by_question_out:
        by_question_method_out[question] = {}
        for method in method_order:
            if method not in by_method:
                continue
            cell = by_question_method.get((question, method), {"qa": 0, "images": set()})
            by_question_method_out[question][method] = {
                "qa": cell["qa"],
                "images": len(cell["images"]),
            }

    return {
        "total_samples": len(rows),
        "total_videos": len(all_videos),
        "total_images": len(all_images),
        "by_method": by_method_out,
        "by_question_type": by_question_out,
        "by_question_method": by_question_method_out,
    }


def _fmt_num(n: int) -> str:
    return f"{n:,}".replace(",", ".")


def write_ddvqa_aggregate_tex(agg: dict, path: str = "outputs/ddvqa_aggregate_table.tex") -> None:
    """Write LaTeX table fragment for tab:ddvqa_aggregate from aggregate stats."""
    method_order = [
        ("Original", "Real"),
        ("Deepfakes", "Fake"),
        ("Face2Face", "Fake"),
        ("FaceSwap", "Fake"),
        ("NeuralTextures", "Fake"),
        ("FaceShifter", "Fake"),
    ]
    lines = [
        "% Auto-generated by scripts/count_dataset_samples.py — do not edit manually.",
        "\\begin{table}[htb]",
        "\\centering",
        "\\caption{DD-VQA (total): vídeos, imagens únicas e amostras de texto por método de manipulação e por tipo de pergunta.}",
        "\\label{tab:ddvqa_aggregate}",
        "\\small",
        "\\begin{tabular}{p{5.6cm}rrr}",
        "\\toprule",
        " & \\textbf{Vídeos} & \\textbf{Imagens} & \\textbf{Texto (QA)} \\\\",
        "\\midrule",
        "\\multicolumn{4}{l}{\\textit{Por método de manipulação}} \\\\",
        "\\midrule",
    ]
    total_v_m = total_i_m = total_q_m = 0
    for method, _tipo in method_order:
        stats = agg["by_method"].get(method, {"videos": 0, "images": 0, "qa": 0})
        v, i, q = stats["videos"], stats["images"], stats["qa"]
        total_v_m += v
        total_i_m += i
        total_q_m += q
        lines.append(f"{method:16s} & {_fmt_num(v)} & {_fmt_num(i)} & {_fmt_num(q)} \\\\")
    lines += [
        "\\midrule",
        f"\\textbf{{Subtotal métodos}} & \\textbf{{{_fmt_num(total_v_m)}}} & \\textbf{{{_fmt_num(total_i_m)}}} & \\textbf{{{_fmt_num(total_q_m)}}} \\\\",
        "\\midrule",
        "\\multicolumn{4}{l}{\\textit{Por tipo de pergunta}} \\\\",
        "\\midrule",
    ]
    total_q_q = 0
    for question, stats in agg["by_question_type"].items():
        v, i, q = stats["videos"], stats["images"], stats["qa"]
        total_q_q += q
        q_tex = question.replace("_", "\\_")
        lines.append(f"{q_tex} & {_fmt_num(v)} & {_fmt_num(i)} & {_fmt_num(q)} \\\\")
    lines += [
        "\\midrule",
        f"\\textbf{{Subtotal perguntas}} & -- & -- & \\textbf{{{_fmt_num(total_q_q)}}} \\\\",
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
    ]
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"LaTeX fragment saved to: {path}")


def write_ddvqa_crosstab_tex(
    agg: dict, path: str = "outputs/ddvqa_by_question_method_table.tex"
) -> None:
    """Write LaTeX table* with QA counts per (question, method)."""
    method_order = [
        "Original", "Deepfakes", "Face2Face", "FaceSwap", "NeuralTextures", "FaceShifter"
    ]
    crosstab = agg.get("by_question_method", {})
    questions = list(agg["by_question_type"].keys())

    lines = [
        "% Auto-generated by scripts/count_dataset_samples.py — do not edit manually.",
        "\\begin{table*}[htb]",
        "\\centering",
        "\\caption{Distribuição de amostras de perguntas e respostas (QA) por tipo de pergunta e método de manipulação no DD-VQA.}",
        "\\label{tab:ddvqa_by_question_method}",
        "\\small",
        "\\begin{tabular}{p{5.6cm}cccccc}",
        "\\toprule",
        "\\textbf{Pergunta} & \\textbf{Original} & \\textbf{Deepfakes} & \\textbf{Face2Face} & \\textbf{FaceSwap} & \\textbf{NeuralTextures} & \\textbf{FaceShifter} \\\\",
        "\\midrule",
    ]

    col_totals = {m: 0 for m in method_order}
    for question in questions:
        q_tex = question.replace("_", "\\_")
        row_cells = []
        for method in method_order:
            stats = crosstab.get(question, {}).get(method, {"qa": 0})
            count = stats["qa"]
            col_totals[method] += count
            row_cells.append(_fmt_num(count))
        lines.append(f"{q_tex} & {' & '.join(row_cells)} \\\\")

    lines += [
        "\\midrule",
        "\\textbf{Total} & "
        + " & ".join(_fmt_num(col_totals[m]) for m in method_order)
        + " \\\\",
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table*}",
    ]
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"LaTeX crosstab saved to: {path}")


def count_jsonl(path: str) -> dict:
    """Count samples in a JSONL file by method and label."""
    if not os.path.isfile(path):
        return None

    rows = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                rows.append(json.loads(line))

    total = len(rows)
    by_method = Counter()
    by_label = Counter()
    by_method_label = Counter()

    by_question_type = Counter()

    for r in rows:
        method = r.get("method", "unknown")
        is_real = r.get("is_real", None)
        if is_real is None:
            label_val = r.get("label", None)
            if label_val is not None:
                is_real = (label_val == 0)
            else:
                answer = r.get("answer", "")
                is_real = "real" in answer.lower()

        label = "real" if is_real else "fake"
        by_method[method] += 1
        by_label[label] += 1
        by_method_label[(method, label)] += 1

        # Classify question type for DD-VQA
        question = r.get("question", "")
        if question:
            q_lower = question.strip().lower()
            if "real or fake" in q_lower or "is this image real" in q_lower or "authentic" in q_lower:
                by_question_type["binary (real/fake)"] += 1
            elif "describe" in q_lower or "explain" in q_lower:
                by_question_type["description/explanation"] += 1
            elif "where" in q_lower or "region" in q_lower or "location" in q_lower or "which part" in q_lower:
                by_question_type["localization (where)"] += 1
            elif "what" in q_lower and ("manipulat" in q_lower or "tamper" in q_lower or "forgery" in q_lower):
                by_question_type["manipulation type (what)"] += 1
            elif "how" in q_lower:
                by_question_type["how (method)"] += 1
            else:
                # Use first 80 chars as key for unclassified
                by_question_type[question[:80].strip()] += 1

    # Count unique videos
    video_ids = set(r.get("video_id", "") for r in rows if r.get("video_id"))

    return {
        "total_samples": total,
        "total_videos": len(video_ids),
        "by_label": dict(by_label),
        "by_method": by_method.most_common(),
        "by_method_label": sorted(
            [(f"{method} ({label})", count)
             for (method, label), count in by_method_label.items()]
        ),
        "by_question_type": by_question_type.most_common(),
    }


def main():
    print("=" * 80)
    print("DATASET SAMPLE COUNTS")
    print("=" * 80)

    all_results = {}

    for name, path in DATASET_PATHS.items():
        result = count_jsonl(path)
        if result is None:
            print(f"\n--- {name} ---")
            print(f"  FILE NOT FOUND: {path}")
            continue

        all_results[name] = result
        print(f"\n--- {name} ---")
        print(f"  File: {path}")
        print(f"  Total samples: {result['total_samples']}")
        print(f"  Unique videos: {result['total_videos']}")
        print(f"  By label: real={result['by_label'].get('real', 0)}, fake={result['by_label'].get('fake', 0)}")
        print(f"  By method:")
        for method, count in result['by_method']:
            print(f"    {method:20s}: {count}")
        print(f"  By method+label:")
        for key, count in result['by_method_label']:
            print(f"    {key:35s}: {count}")
        if result['by_question_type']:
            print(f"  By question type:")
            for qtype, count in result['by_question_type']:
                print(f"    {qtype:40s}: {count}")

    # Summary table
    print("\n" + "=" * 80)
    print("SUMMARY TABLE")
    print("=" * 80)
    print(f"{'Dataset':<35s} {'Total':>8} {'Real':>8} {'Fake':>8} {'Videos':>8}")
    print("-" * 75)
    for name, result in all_results.items():
        print(
            f"{name:<35s} "
            f"{result['total_samples']:>8} "
            f"{result['by_label'].get('real', 0):>8} "
            f"{result['by_label'].get('fake', 0):>8} "
            f"{result['total_videos']:>8}"
        )

    # DD-VQA aggregate (train + val + test)
    ddvqa_paths = [
        DATASET_PATHS["DD-VQA (train)"],
        DATASET_PATHS["DD-VQA (val)"],
        DATASET_PATHS["DD-VQA (test)"],
    ]
    agg = count_ddvqa_aggregate(ddvqa_paths)
    if agg:
        all_results["DD-VQA (aggregate)"] = agg
        print("\n--- DD-VQA (aggregate: train + val + test) ---")
        print(f"  Total QA: {agg['total_samples']}")
        print(f"  Unique images: {agg['total_images']}")
        print(f"  Unique videos: {agg['total_videos']}")
        print("  By method (videos / images / QA):")
        for method, stats in agg["by_method"].items():
            print(
                f"    {method:16s}: "
                f"videos={stats['videos']:4d}  images={stats['images']:4d}  qa={stats['qa']:5d}"
            )
        print("  By question type (videos / images / QA):")
        for question, stats in agg["by_question_type"].items():
            q_short = question[:50] + ("..." if len(question) > 50 else "")
            print(
                f"    {q_short:53s}: "
                f"v={stats['videos']:4d}  i={stats['images']:4d}  qa={stats['qa']:5d}"
            )
        write_ddvqa_aggregate_tex(agg)
        write_ddvqa_crosstab_tex(agg)

    # Save as JSON (convert tuples to dicts for serialization)
    output_path = "outputs/dataset_counts.json"
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    json_results = {}
    for name, result in all_results.items():
        if name == "DD-VQA (aggregate)":
            json_results[name] = result
            continue
        json_results[name] = {
            "total_samples": result["total_samples"],
            "total_videos": result["total_videos"],
            "by_label": result["by_label"],
            "by_method": {m: c for m, c in result["by_method"]},
            "by_method_label": {k: c for k, c in result["by_method_label"]},
            "by_question_type": {q: c for q, c in result["by_question_type"]},
        }
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(json_results, f, indent=2, ensure_ascii=False)
    print(f"\nJSON report saved to: {output_path}")


if __name__ == "__main__":
    main()
