def count_jsonl(path: str) -> dict:
    """Count samples in a JSONL file by method and label."""
    if not os.path.isfile(path):
        return None

    rows = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                rows.append(json.loads(line))

    total = len(rows)
    by_method = Counter()
    by_label = Counter()
    by_method_label = Counter()

    by_question_type = Counter()
    unique_images: set[str] = set()
    unique_images_by_label: dict[str, set[str]] = defaultdict(set)
    unique_images_by_method: dict[str, set[str]] = defaultdict(set)
    unique_instances: set[tuple[str, str]] = set()

    for r in rows:
        method = r.get("method", "unknown")
        is_real = r.get("is_real", None)
        if is_real is None:
            label_val = r.get("label", None)
            if label_val is not None:
                is_real = (label_val == 0)
            else:
                answer = r.get("answer", "")
                is_real = "real" in answer.lower()

        label = "real" if is_real else "fake"
        by_method[method] += 1
        by_label[label] += 1
        by_method_label[(method, label)] += 1

        image = r.get("image", "")
        video_id = r.get("video_id", "")
        if image:
            unique_images.add(image)
            unique_images_by_label[label].add(image)
            unique_images_by_method[method].add(image)
        if method and video_id:
            unique_instances.add((method, video_id))

        # Classify question type for DD-VQA
        question = r.get("question", "")
        if question:
            q_lower = question.strip().lower()
            if "real or fake" in q_lower or "is this image real" in q_lower or "authentic" in q_lower:
                by_question_type["binary (real/fake)"] += 1
            elif "describe" in q_lower or "explain" in q_lower:
                by_question_type["description/explanation"] += 1
            elif "where" in q_lower or "region" in q_lower or "location" in q_lower or "which part" in q_lower:
                by_question_type["localization (where)"] += 1
            elif "what" in q_lower and ("manipulat" in q_lower or "tamper" in q_lower or "forgery" in q_lower):
                by_question_type["manipulation type (what)"] += 1
            elif "how" in q_lower:
                by_question_type["how (method)"] += 1
            else:
                # Use first 80 chars as key for unclassified
                by_question_type[question[:80].strip()] += 1

    # Unique source video IDs (may be shared across manipulation methods)
    video_ids = set(r.get("video_id", "") for r in rows if r.get("video_id"))

    return {
        "total_samples": total,
        "total_videos": len(video_ids),
        "total_instances": len(unique_instances) or len(unique_images),
        "total_images": len(unique_images),
        "by_label": dict(by_label),
        "by_label_instances": {k: len(v) for k, v in unique_images_by_label.items()},
        "by_method_instances": {m: len(v) for m, v in unique_images_by_method.items()},
        "by_method": by_method.most_common(),
        "by_method_label": sorted(
            [(f"{method} ({label})", count)
             for (method, label), count in by_method_label.items()]
        ),
        "by_question_type": by_question_type.most_common(),
    }


def main():
    print("=" * 80)
    print("DATASET SAMPLE COUNTS")
    print("=" * 80)

    all_results = {}

    for name, path in DATASET_PATHS.items():
        result = count_jsonl(path)
        if result is None:
            print(f"\n--- {name} ---")
            print(f"  FILE NOT FOUND: {path}")
            continue

        all_results[name] = result
        print(f"\n--- {name} ---")
        print(f"  File: {path}")
        print(f"  Total samples: {result['total_samples']}")
        print(f"  Unique videos: {result['total_videos']}")
        print(f"  By label: real={result['by_label'].get('real', 0)}, fake={result['by_label'].get('fake', 0)}")
        print(f"  By method:")
        for method, count in result['by_method']:
            print(f"    {method:20s}: {count}")
        print(f"  By method+label:")
        for key, count in result['by_method_label']:
            print(f"    {key:35s}: {count}")
        if result['by_question_type']:
            print(f"  By question type:")
            for qtype, count in result['by_question_type']:
                print(f"    {qtype:40s}: {count}")

    # Summary table
    print("\n" + "=" * 80)
    print("SUMMARY TABLE")
    print("=" * 80)
    print(f"{'Dataset':<35s} {'Total':>8} {'Real':>8} {'Fake':>8} {'Videos':>8}")
    print("-" * 75)
    for name, result in all_results.items():
        print(
            f"{name:<35s} "
            f"{result['total_samples']:>8} "
            f"{result['by_label'].get('real', 0):>8} "
            f"{result['by_label'].get('fake', 0):>8} "
            f"{result['total_videos']:>8}"
        )

    # DD-VQA aggregate (train + val + test)
    ddvqa_paths = [
        DATASET_PATHS["DD-VQA (train)"],
        DATASET_PATHS["DD-VQA (val)"],
        DATASET_PATHS["DD-VQA (test)"],
    ]
    agg = count_ddvqa_aggregate(ddvqa_paths)
    if agg:
        all_results["DD-VQA (aggregate)"] = agg
        print("\n--- DD-VQA (aggregate: train + val + test) ---")
        print(f"  Total QA: {agg['total_samples']}")
        print(f"  Unique images: {agg['total_images']}")
        print(f"  Unique videos: {agg['total_videos']}")
        print("  By method (videos / images / QA):")
        for method, stats in agg["by_method"].items():
            print(
                f"    {method:16s}: "
                f"videos={stats['videos']:4d}  images={stats['images']:4d}  qa={stats['qa']:5d}"
            )
        print("  By question type (videos / images / QA):")
        for question, stats in agg["by_question_type"].items():
            q_short = question[:50] + ("..." if len(question) > 50 else "")
            print(
                f"    {q_short:53s}: "
                f"v={stats['videos']:4d}  i={stats['images']:4d}  qa={stats['qa']:5d}"
            )
        write_ddvqa_aggregate_tex(agg)
        write_ddvqa_crosstab_tex(agg)

    write_unified_dataset_counts_tex(all_results)

    # Save as JSON (convert tuples to dicts for serialization)
    output_path = "outputs/dataset_counts.json"
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    json_results = {}
    for name, result in all_results.items():
        if name == "DD-VQA (aggregate)":
            json_results[name] = result
            continue
        json_results[name] = {
            "total_samples": result["total_samples"],
            "total_videos": result["total_videos"],
            "total_instances": result["total_instances"],
            "total_images": result["total_images"],
            "by_label": result["by_label"],
            "by_label_instances": result["by_label_instances"],
            "by_method_instances": result["by_method_instances"],
            "by_method": {m: c for m, c in result["by_method"]},
            "by_method_label": {k: c for k, c in result["by_method_label"]},
            "by_question_type": {q: c for q, c in result["by_question_type"]},
        }
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(json_results, f, indent=2, ensure_ascii=False)
    print(f"\nJSON report saved to: {output_path}")


if __name__ == "__main__":
    main()
